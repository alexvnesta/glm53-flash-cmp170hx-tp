"""Two-sequence continuous batching on upstream ExLlamaV3's native sliding-window DFlash2 draft state (P16 stage 2).

Upstream (7de419b) gives every job a PairedState: the target's recurrent (KDA) state and the drafter's SWAState,
one window ring per state slot, checkpointed and restored together. Draft custody is therefore native: no draft
block table, no shared paged draft cache, no per-job partition to lease or prove. This module keeps only service
policy: admission, the persistent step/thread owner, the P14c embedding drop, observation counters and the bridge
to the B2 terminal latch. It replaces glm_concurrent_ring (stage 1, -swa_full). Importing does not load Torch or
initialize CUDA.
"""
