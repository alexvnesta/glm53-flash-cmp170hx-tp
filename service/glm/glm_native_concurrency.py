def verify_engine_sources(root):
    root = Path(root).resolve(strict=True)
    for relative, expected in ENGINE_SOURCE_PINS.items():
        path = root / relative
        if path.resolve(strict=True) != path or hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise ValueError(f"Concurrent engine source mismatch: {relative}")


# exllamav3/tokenizer/mm_embedding.py (hash-pinned with generator.py and job.py by glm_vision.load_tower)
FIRST_MM_EMBEDDING_INDEX = 1000000000


def _active_host():
    return os.environ.get('GLM53_TP_ACTIVE_HOST', '0') not in ('', '0')


class NativeConcurrency:
    def __init__(self, generator, slots, allow_embeddings=False, drop_embeddings=False, allow_json_output=False):
        if type(slots) is not int or not 2 <= slots <= 8:
            raise ValueError("Concurrent slots must be 2..8")
        if type(allow_embeddings) is not bool:
            raise ValueError("allow_embeddings must be a bool")
        if type(drop_embeddings) is not bool or (drop_embeddings and not allow_embeddings):
            raise ValueError("drop_embeddings must be a bool and needs allow_embeddings")
        if type(allow_json_output) is not bool:
            raise ValueError("allow_json_output must be a bool")
        self.allow_json_output = allow_json_output
        g = generator
        draft = g.draft_cache
        if (not g.dflash_draft or not getattr(g, 'draft_recurrent', False) or not g.model.loaded_tp
                or g.max_batch_size != slots or getattr(draft, 'num_slots', None) != slots
                or g.recurrent_cache is None or g.cache.num_slots < slots
                or g.enable_defrag or g.num_remaining_jobs()
                or getattr(g.pagetable, 'cpu_tier', None) is not None
                or getattr(g, '_glm_tp_active_host_coordinator', None) is not None
                or getattr(g.model, '_glm_tp_active_host_coordinator', None) is not None or _active_host()):
            raise ValueError("Native concurrency requires idle TP, a sliding-window DFlash2 draft state (no -swa_full), "
                             "exact batch/state capacity, no defrag or tier")
        # The drafter's window rings: one SWALayerState per sliding layer, `slots` rings each (upstream allocates
        # them once at load; a job owns one ring slot from Job.allocate_pages until deallocate_pages)
        layers = list(getattr(draft, 'recurrent_layers', {}).values())
        geometry = {(getattr(l, 'max_batch_size', None), l.module.kv_state_size, l.module.sliding_window) for l in layers}
        if not layers or len(geometry) != 1 or next(iter(geometry))[0] != slots:
            raise ValueError("Native draft window rings do not match the concurrent slot count")
        self.generator = g
        self._paired_owner = None
        self.model = g.model
        self.target_cache = g.cache
        self.draft_model = g.draft_model
        self.draft_cache = draft
        self.draft_layers = draft.recurrent_layers
        self.native = g.recurrent_cache
        self.pagetable = g.pagetable
        self.all_pages = g.pagetable.all_pages
        self.pages = tuple(self.all_pages)
        self.cache_serial = g.cache_owner_serial
        self.target_tokens = g.cache.max_num_tokens
        self.native_slots = g.cache.num_slots
        self.slots = slots
        _, self.draft_state_rows, self.draft_window = next(iter(geometry))
        self.draft_state_bytes = sum(int(l.storage_size()) for l in layers)
        self.thread = None
        self.depth = 0
        self.prefill_job = None
        self.closed = False
        self.peak_leases = 0
        self.batched_draft_rounds = 0
        self.peak_draft_batch = 0
        self.peak_target_batch = 0
        self.batched_verifier_rounds = 0
        self.mixed_prefill_steps = 0
        self.reused_slots = 0
        self.decode_table_rebinds = 0
        self.ever_used = set()
        # --experimental-vision: image jobs carry MMEmbeddings (content-cached, so equal ids mean equal content).
        self.allow_embeddings = allow_embeddings
        # P14c: set a job's embeddings aside once its prompt is prefilled (drop_prefilled_embeddings).
        self.drop_embeddings = drop_embeddings
        self.embeddings_dropped = 0

    def _ownership_error(self, error):
        paired = self._paired_owner
        if paired is not None:
            paired._terminal(paired.failure or error)
        raise error

    def check_owner(self, transfer=False):
        paired = self._paired_owner
        if paired is not None and paired.failure is not None:
            self._ownership_error(paired.failure)
        try:
            return self._check_owner(transfer=transfer)
        except Exception as error:
            # Only the exact published paired owner converts proof loss to shared quarantine.
            self._ownership_error(error)

    def _check_owner(self, transfer=False):
        g = self.generator
        tier = None if self._paired_owner is None else self._paired_owner.tier
        if (self.closed or getattr(g, "_glm_b2_retention", None) is not self._paired_owner
                or g.model is not self.model or g.cache is not self.target_cache or not g.model.loaded_tp
                or g.draft_model is not self.draft_model or self.draft_cache.model is not self.draft_model
                or g.draft_cache is not self.draft_cache or not g.draft_recurrent
                or self.draft_cache.recurrent_layers is not self.draft_layers
                or self.draft_cache.num_slots != self.slots
                or g.recurrent_cache is not self.native
                or g.pagetable is not self.pagetable
                or self.pagetable.generator is not g or self.pagetable.cache is not self.target_cache
                or self.pagetable.all_pages is not self.all_pages
                or len(self.all_pages) != len(self.pages)
                or any(a is not b or a.page_index != i for i, (a, b) in enumerate(zip(self.all_pages, self.pages)))
                or g.cache_owner_serial != self.cache_serial
                or getattr(g.cache, 'owner_serial', None) != self.cache_serial
                or g.max_batch_size != self.slots or g.enable_defrag
                or g.cache.max_num_tokens != self.target_tokens
                or g.cache.num_slots != self.native_slots
                or getattr(self.pagetable, 'cpu_tier', None) is not tier
                or getattr(g, 'cpu_page_cache', None) is not tier
                or getattr(g, '_glm_tp_active_host_coordinator', None) is not None
                or getattr(g.model, '_glm_tp_active_host_coordinator', None) is not None or _active_host()):
            raise RuntimeError("Native concurrency owner or cache geometry changed")
        if transfer and (self.depth != 1 or self.thread != threading.get_ident()):
            raise RuntimeError("Native concurrency transfer is outside the persistent step owner")

    @contextmanager
    def step(self):
        self.check_owner()
        thread = threading.get_ident()
        if self.thread is None:
            self.thread = thread
        if self.thread != thread or self.depth:
            self._ownership_error(RuntimeError("Concurrent generator step owner changed or nested"))
        self.depth = 1
        try:
            self.check_owner(transfer=True)
            yield
        finally:
            self.prefill_job = None
            self.depth = 0

    @contextmanager
    def prefill(self, job):
        self.check_owner(transfer=True)
        if self.prefill_job is not None:
            raise RuntimeError("Nested concurrent prefill")
        self.prefill_job = job
        try:
            yield
        finally:
            self.prefill_job = None

    def prepare(self, job):
        """The one admission check, after native hashing and before the job joins pending_jobs."""
        self.check_owner()
        if (job.generator is not self.generator or job.pagetable is not self.pagetable
                or len(job.sequences) != 1 or job.is_requeued or (job.embeddings and not self.allow_embeddings)
                or job.banned_strings or job.prefix_token is not None
                or job.orig_max_rq_tokens is not None):
            raise ValueError("Concurrent profile supports plain, non-requeued single-sequence jobs")
        if job.filters:
            from glm_json_output import permitted_filters
            if not self.allow_json_output or not permitted_filters(job.filters, self.generator.tokenizer, job):
                raise ValueError("Concurrent profile only permits its explicitly enabled JSON-object filter")

    def held_slots(self):
        """Draft ring slots held by jobs (upstream's own free list; safe to read from the HTTP thread)."""
        return self.slots - len(self.draft_cache.free_list)

    def check_slots(self):
        """Every active job holds its own target and draft slot, and no slot is held outside the active jobs."""
        g = self.generator
        pairs = [job.recurrent_state for job in g.active_jobs if job.recurrent_state is not None]
        draft = [p.draft.slot for p in pairs if p.draft is not None]
        target = [p.target.slot for p in pairs if p.target is not None]
        if (len(draft) != len(pairs) or len(target) != len(pairs) or len(set(draft)) != len(draft)
                or len(set(target)) != len(target) or any(p.draft.cache is not self.draft_cache for p in pairs)
                or self.held_slots() != len(pairs) or g.cache.num_slots - len(g.cache.free_list) != len(pairs)):
            self._ownership_error(RuntimeError("Native recurrent slot custody does not match the active jobs"))

    def allocated(self, job):
        """After a native allocation returned: slot reuse and peak observations."""
        self.check_slots()
        slot = job.recurrent_state.draft.slot
        self.reused_slots += slot in self.ever_used
        self.ever_used.add(slot)
        self.peak_leases = max(self.peak_leases, self.held_slots())

    def snapshot_tables(self, jobs):
        return [job.sequences[0].block_index_tensor for job in jobs]

    def observe_decode(self, jobs, tables, drafted):
        # Native completed-page dedupe (Job.hash_completed_page) rebuilds a row's target block table during
        # sampling. The native draft path reads no block table, so this is an observation only (P13 retired).
        self.decode_table_rebinds += sum(job.sequences[0].block_index_tensor is not table
                                         for job, table in zip(jobs, tables))
        rows = len(jobs)
        self.peak_target_batch = max(self.peak_target_batch, rows)
        self.batched_verifier_rounds += rows > 1
        if drafted:
            self.peak_draft_batch = max(self.peak_draft_batch, rows)
            self.batched_draft_rounds += rows > 1

    def stats(self):
        return dict(mode='native_swa', max_sequences=self.slots,
                    active_ring_leases=self.held_slots(), peak_ring_leases=self.peak_leases,
                    peak_draft_batch=self.peak_draft_batch,
                    batched_draft_rounds=self.batched_draft_rounds,
                    peak_target_batch=self.peak_target_batch,
                    batched_verifier_rounds=self.batched_verifier_rounds,
                    mixed_prefill_steps=self.mixed_prefill_steps, reused_slots=self.reused_slots,
                    decode_table_rebinds=self.decode_table_rebinds,
                    paired_retention=self._paired_owner is not None,
                    json_object_filters=self.allow_json_output,
                    draft_state_rows=self.draft_state_rows, draft_window=self.draft_window,
                    draft_state_bytes=self.draft_state_bytes,
                    **({"embeddings_dropped": self.embeddings_dropped} if self.allow_embeddings else {}))

    def drop_prefilled_embeddings(self, jobs):
        """P14c. The native decode batch passes every active job's embeddings on every step (generator.iterate_gen),
        which under TP copies them into the worker arena each time. After prefill nothing reads them: GLM-5 has no
        MRoPE, ring jobs are never requeued (prepare refuses it), and only MTP drafting feeds them to a draft model.
        A job keeps them while any image id is still unfed. The list object stays with the content cache."""
        if self.generator.mtp_draft or self.model.caps.get("mrope"):
            return
        for job in jobs:
            if not job.embeddings:
                continue
            unfed = [seq.sequence_ids.torch_slice(seq.kv_position, None) for seq in job.sequences]
            if any(ids.numel() and int(ids.max()) >= FIRST_MM_EMBEDDING_INDEX for ids in unfed):
                continue
            job.embeddings = []
            self.embeddings_dropped += 1

    def close(self):
        self.closed = True


def install_native_concurrency(slots=2):
    """Install instance-gated Job/Generator hooks before model initialization (no cache or drafter hook)."""
    from exllamav3.generator.generator import Generator
    from exllamav3.generator.job import Job
    import exllamav3
    verify_engine_sources(Path(exllamav3.__file__).resolve().parent.parent)
    if _active_host():
        raise ValueError("Native concurrency excludes TP active-host migration")
    if type(slots) is not int or not 2 <= slots <= 8:
        raise ValueError("Native concurrency requires 2..8 slots")
    installed = getattr(Job.prepare_for_queue, '_glm_native_concurrency', None)
    if installed is not None:
        if installed != slots:
            raise ValueError("Native concurrency was already installed with different capacity")
        return

    prepare, allocate, prefill, deallocate = Job.prepare_for_queue, Job.allocate_pages, Job.prefill, Job.deallocate_pages
    stash = Job.maybe_stash_recurrent
    cancel, clear_queue = Generator.cancel, Generator.clear_queue
    iterate, iterate_gen, close = Generator.iterate, Generator.iterate_gen, Generator.close
    idle_work = Generator.idle_work
    def prepare_hook(self, g, *args, **kwargs):
        result = prepare(self, g, *args, **kwargs)
        manager = getattr(g, '_glm_native_concurrency', None)
        if manager is not None:
            manager.prepare(self)
            paired = getattr(g, "_glm_b2_retention", None)
            if paired is not None:
                paired.prepare(self)
        return result
    def allocate_hook(self):
        manager = getattr(self.generator, '_glm_native_concurrency', None)
        if manager is None:
            return allocate(self)
        manager.check_owner(transfer=True)
        paired = getattr(self.generator, "_glm_b2_retention", None)
        result = allocate(self) if paired is None else paired.allocate(self, allocate, deallocate)
        manager.allocated(self)
        return result
    def prefill_hook(self, results, *args, **kwargs):
        manager = getattr(self.generator, '_glm_native_concurrency', None)
        if manager is None:
            return prefill(self, results, *args, **kwargs)
        mixed = any(job is not self and job.is_prefill_done() for job in self.generator.active_jobs)
        before = len(results)
        from glm_replay_quarantine import RecurrentReplayError
        try:
            with manager.prefill(self):
                paired = getattr(self.generator, "_glm_b2_retention", None)
                shared = None if paired is None else paired.shared
                result = (prefill(self, results, *args, **kwargs) if shared is None else
                          shared.prefill(self, results, prefill, *args, **kwargs))
        except RecurrentReplayError as error:
            paired = getattr(self.generator, "_glm_b2_retention", None)
            if paired is not None:
                paired._terminal(error)
            raise
        if mixed and any(event.get('stage') == 'prefill' for event in results[before:]):
            manager.mixed_prefill_steps += 1
        return result
    def deallocate_hook(self):
        paired = getattr(self.generator, "_glm_b2_retention", None)
        if paired is not None:
            return paired.deallocate(self, deallocate)
        return deallocate(self)
    def iterate_hook(self):
        manager = getattr(self, '_glm_native_concurrency', None)
        if manager is None:
            return iterate(self)
        from glm_b2_native import StopSharedGeneration, shared_failure
        try:
            with manager.step():
                result = iterate(self)
                paired = getattr(self, "_glm_b2_retention", None)
                if paired is not None:
                    paired.finish(result)
                return result
        except StopSharedGeneration as error:
            raise shared_failure(error) from error
    def iterate_gen_hook(self, results, draft_tokens=None):
        manager = getattr(self, '_glm_native_concurrency', None)
        if manager is None:
            return iterate_gen(self, results, draft_tokens)
        manager.check_owner(transfer=True)
        manager.check_slots()
        jobs = [job for job in self.active_jobs if job.is_prefill_done()]
        if manager.drop_embeddings:
            manager.drop_prefilled_embeddings(jobs)
        tables = manager.snapshot_tables(jobs)
        from glm_replay_quarantine import RecurrentReplayError
        try:
            result = iterate_gen(self, results, draft_tokens)
        except RecurrentReplayError as error:
            paired = getattr(self, "_glm_b2_retention", None)
            if paired is not None:
                paired._terminal(error)
            raise
        manager.observe_decode(jobs, tables, draft_tokens is not None)
        return result
    def stash_hook(self, cache, *args, **kwargs):
        paired = getattr(self.generator, "_glm_b2_retention", None)
        if paired is None:
            return stash(self, cache, *args, **kwargs)
        return paired.stash(self, cache, stash, *args, **kwargs)
    def cancel_hook(self, job):
        paired = getattr(self, "_glm_b2_retention", None)
        if paired is None:
            return cancel(self, job)
        return paired.cancel(job, lambda owned_job: cancel(self, owned_job))
    def clear_hook(self):
        paired = getattr(self, "_glm_b2_retention", None)
        if paired is None:
            return clear_queue(self)
        jobs = tuple(self.active_jobs + self.pending_jobs)
        result = clear_queue(self)
        paired.cleared(jobs)
        return result
    def close_hook(self):
        paired = getattr(self, "_glm_b2_retention", None)
        if paired is None:
            try:
                return close(self)
            finally:
                manager = getattr(self, '_glm_native_concurrency', None)
                if manager is not None:
                    manager.close()
        # The actual async wrapper has settled its uncancellable iteration first. Retire the B2 records only after
        # native close returned with no checkpoints (RecurrentCache.close releases both sides of every pair).
        paired.closing = True
        result = close(self)
        paired = getattr(self, "_glm_b2_retention", None)
        if paired is not None:
            paired.retire_after_native_close()
        manager = getattr(self, '_glm_native_concurrency', None)
        if manager is not None:
            manager.close()
        return result
    def idle_hook(self):
        manager = getattr(self, '_glm_native_concurrency', None)
        if manager is None:
            return idle_work(self)
        from glm_b2_native import StopSharedGeneration, shared_failure
        try:
            with manager.step():
                return idle_work(self)
        except StopSharedGeneration as error:
            raise shared_failure(error) from error
    # The unhooked native prefill, for the start-up fair scheduling check (glm_concurrent_options).
    prefill_hook._glm_native = prefill
    prepare_hook._glm_native_concurrency = slots
    Job.prepare_for_queue, Job.allocate_pages = prepare_hook, allocate_hook
    Job.prefill, Job.deallocate_pages = prefill_hook, deallocate_hook
    Job.maybe_stash_recurrent = stash_hook
    Generator.cancel, Generator.clear_queue = cancel_hook, clear_hook
    Generator.iterate, Generator.iterate_gen, Generator.close = iterate_hook, iterate_gen_hook, close_hook
    Generator.idle_work = idle_hook


def bind_native_concurrency(generator, slots, allow_embeddings=False, drop_embeddings=False, allow_json_output=False):
    old_defrag = generator.enable_defrag
    if generator.num_remaining_jobs() or getattr(generator, '_glm_native_concurrency', None) is not None:
        raise ValueError("Native concurrency requires a fresh idle generator")
    generator.enable_defrag = False
    try:
        manager = NativeConcurrency(generator, slots, allow_embeddings=allow_embeddings,
                                    drop_embeddings=drop_embeddings, allow_json_output=allow_json_output)
        generator._glm_native_concurrency = manager
        return manager
    except BaseException:
        generator.enable_defrag = old_defrag
        raise
